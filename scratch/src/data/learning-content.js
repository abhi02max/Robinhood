const STAGES = ['Beginner', 'Intermediate', 'Advanced', 'Interview', 'Industry Use Cases'];

function topic(id, title, stage, cfg) {
  return {
    id,
    title,
    stage,
    estimatedMins: cfg.estimatedMins || 18,
    content: {
      beginnerExplanation: cfg.beginnerExplanation,
      intuition: cfg.intuition,
      analogy: cfg.analogy,
      realWorldUse: cfg.realWorldUse,
      diagram: cfg.diagram,
      example: cfg.example,
      interviewQuestions: cfg.interviewQuestions || [],
      companyUsageExamples: cfg.companyUsageExamples || [],
      commonMistakes: cfg.commonMistakes || [],
      revisionNotes: cfg.revisionNotes || [],
    },
    practiceQuestions: cfg.practiceQuestions || [],
    quiz: cfg.quiz || [],
  };
}

function buildDepthAppendix(subjectTitle, topicTitle, stage) {
  return `In ${subjectTitle}, "${topicTitle}" is best learned in three passes: first build vocabulary, then model failure cases, then reason about trade-offs under scale and constraints. At the ${stage} stage, focus on why one approach is chosen over another, which assumptions can break in production, and how observability or debugging evidence validates your design choices.`;
}

function enrichLearningTopics(topics, subjectTitle) {
  return topics.map((t) => {
    const c = t.content || {};
    return {
      ...t,
      estimatedMins: Math.max(Number(t.estimatedMins || 18), 26),
      content: {
        ...c,
        beginnerExplanation: `${c.beginnerExplanation} ${buildDepthAppendix(subjectTitle, t.title, t.stage)}`,
        intuition: `${c.intuition} Always connect the intuition to measurable outcomes such as latency, throughput, consistency, or maintainability so your reasoning is interview-ready and production-aware.`,
        realWorldUse: `${c.realWorldUse} In real teams, this concept is paired with runbooks, dashboards, and incident reviews so engineers can diagnose regressions quickly and defend architecture decisions with evidence.`,
        example: `${c.example} Also analyze one edge variant where constraints change (higher scale, partial failure, noisy input, or tighter latency) and explain how your approach adapts.`,
        interviewQuestions: [
          ...(c.interviewQuestions || []),
          `How would you explain ${t.title} to a junior engineer and then deepen it for a senior interviewer?`,
          `What trade-offs would you choose for ${t.title} under high scale, strict latency, and failure scenarios?`,
        ],
        companyUsageExamples: [
          ...(c.companyUsageExamples || []),
          `Production playbook: teams instrument ${t.title} with metrics, traces, and alerts before optimization.`,
        ],
        commonMistakes: [
          ...(c.commonMistakes || []),
          `Explaining ${t.title} as a definition only, without constraints, trade-offs, or failure analysis.`,
        ],
        revisionNotes: [
          ...(c.revisionNotes || []),
          `Revision heuristic: explain ${t.title} from basics, then compare at least two alternatives with explicit trade-offs.`,
        ],
      },
      practiceQuestions: [
        ...(t.practiceQuestions || []),
        `Design a mini case study using ${t.title} and justify the trade-offs with constraints.`,
        `List failure modes for ${t.title} and propose detection + mitigation steps.`,
      ],
      quiz: (t.quiz && t.quiz.length)
        ? t.quiz
        : [{
            q: `What is the most reliable way to evaluate decisions in "${t.title}"?`,
            options: [
              'Pick the most popular approach',
              'Use constraints + trade-offs + measurable outcomes',
              'Optimize one metric only',
              'Ignore failure scenarios',
            ],
            answerIndex: 1,
          }],
    };
  });
}

