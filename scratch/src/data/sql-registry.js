// ── Lookup helpers ────────────────────────────

export function getSqlTopic(topicId) {
  return SQL_TOPICS.find(t => t.id === topicId) || null;
}

export function getSqlProblem(problemId) {
  return SQL_PROBLEMS.find(p => p.id === problemId) || null;
}

export function getSqlProblemsByTopic(topicId) {
  return SQL_PROBLEMS.filter(p => p.topicId === topicId);
}

export function getSqlTopicStats(topicId) {
  const problems = getSqlProblemsByTopic(topicId);
  return {
    total: problems.length,
    easy: problems.filter(p => p.difficulty === 'Easy').length,
    medium: problems.filter(p => p.difficulty === 'Medium').length,
    hard: problems.filter(p => p.difficulty === 'Hard').length,
  };
}

export const SQL_COMPANIES = [...new Set(SQL_PROBLEMS.flatMap(p => p.companies))].sort();

